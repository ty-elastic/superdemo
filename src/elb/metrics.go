package main

import (
	"sync"
	"sync/atomic"
)

// WindowSnapshot holds the aggregated metric values for one 5-second flush window.
type WindowSnapshot struct {
	// Counter metrics (reset to 0 after each Snapshot).
	RequestCount   int64
	TargetRequests int64 // requests routed to a target (basis for RequestCountPerTarget)
	ProcessedBytes int64
	NewConnections int64
	ELB3XX         int64
	ELB4XX         int64
	ELB5XX         int64
	ELB503         int64
	Tgt2XX         int64
	Tgt3XX         int64
	Tgt4XX         int64
	Tgt5XX         int64

	// TargetResponseTime accumulators (reset after each Snapshot).
	TRTSum   float64
	TRTCount int64
	TRTMax   float64

	// Gauge metrics (read without reset).
	ActiveConnections int64

	// Health state (read from the backend pool at snapshot time).
	HealthyHosts   int
	UnhealthyHosts int
}

// lbAgg accumulates per-request metrics for one load balancer.
// The hot path uses lock-free atomics for counters; a small mutex
// guards the float accumulators.
type lbAgg struct {
	requestCount   atomic.Int64
	targetRequests atomic.Int64
	processedBytes atomic.Int64
	newConns       atomic.Int64
	elb3xx         atomic.Int64
	elb4xx         atomic.Int64
	elb5xx         atomic.Int64
	elb503         atomic.Int64
	tgt2xx         atomic.Int64
	tgt3xx         atomic.Int64
	tgt4xx         atomic.Int64
	tgt5xx         atomic.Int64
	activeConns    atomic.Int64 // gauge: open client connections

	mu       sync.Mutex
	trtSum   float64
	trtCount int64
	trtMax   float64
}

func newLBAgg() *lbAgg {
	return &lbAgg{}
}

// ConnOpened records a new client TCP connection (NewConnectionCount, ActiveConnectionCount).
func (a *lbAgg) ConnOpened() {
	a.newConns.Add(1)
	a.activeConns.Add(1)
}

// ConnClosed records a client TCP connection closing (or being hijacked).
func (a *lbAgg) ConnClosed() { a.activeConns.Add(-1) }

// RecordRequest records the outcome of a completed (or failed) proxied request.
//
//   - backendURL: empty string if no backend was selected (503 case).
//   - statusCode: final HTTP status code returned to the client.
//   - reqBytes / respBytes: bytes transferred.
//   - targetSec: backend response latency in seconds; negative if not applicable.
//   - isProxyError: true when the ELB itself generated the error (connection failure, 503, etc.).
func (a *lbAgg) RecordRequest(backendURL string, statusCode int, reqBytes, respBytes int64, targetSec float64, isProxyError bool) {
	a.requestCount.Add(1)
	a.processedBytes.Add(reqBytes + respBytes)
	if backendURL != "" {
		a.targetRequests.Add(1)
	}

	if isProxyError {
		// Load-balancer-generated response. As in AWS, HTTPCode_ELB_503_Count is
		// a subset of HTTPCode_ELB_5XX_Count.
		switch {
		case statusCode >= 500:
			a.elb5xx.Add(1)
			if statusCode == 503 {
				a.elb503.Add(1)
			}
		case statusCode >= 400:
			a.elb4xx.Add(1)
		case statusCode >= 300:
			a.elb3xx.Add(1)
		}
	} else {
		// Response generated by the target and passed through unchanged.
		switch {
		case statusCode >= 500:
			a.tgt5xx.Add(1)
		case statusCode >= 400:
			a.tgt4xx.Add(1)
		case statusCode >= 300:
			a.tgt3xx.Add(1)
		case statusCode >= 200:
			a.tgt2xx.Add(1)
		}
	}

	if targetSec >= 0 && backendURL != "" {
		a.mu.Lock()
		a.trtSum += targetSec
		a.trtCount++
		if targetSec > a.trtMax {
			a.trtMax = targetSec
		}
		a.mu.Unlock()
	}
}

// Snapshot reads-and-zeros all counter-type metrics and returns them along with
// a read of the current gauge and health state.
// The activeConns gauge is NOT reset (it is maintained continuously).
func (a *lbAgg) Snapshot(pool *BackendPool) WindowSnapshot {
	a.mu.Lock()
	trtSum := a.trtSum
	trtCount := a.trtCount
	trtMax := a.trtMax
	a.trtSum = 0
	a.trtCount = 0
	a.trtMax = 0
	a.mu.Unlock()

	return WindowSnapshot{
		RequestCount:      a.requestCount.Swap(0),
		TargetRequests:    a.targetRequests.Swap(0),
		ProcessedBytes:    a.processedBytes.Swap(0),
		NewConnections:    a.newConns.Swap(0),
		ELB3XX:            a.elb3xx.Swap(0),
		ELB4XX:            a.elb4xx.Swap(0),
		ELB5XX:            a.elb5xx.Swap(0),
		ELB503:            a.elb503.Swap(0),
		Tgt2XX:            a.tgt2xx.Swap(0),
		Tgt3XX:            a.tgt3xx.Swap(0),
		Tgt4XX:            a.tgt4xx.Swap(0),
		Tgt5XX:            a.tgt5xx.Swap(0),
		TRTSum:            trtSum,
		TRTCount:          trtCount,
		TRTMax:            trtMax,
		ActiveConnections: a.activeConns.Load(),
		HealthyHosts:      pool.HealthyCount(),
		UnhealthyHosts:    pool.UnhealthyCount(),
	}
}
